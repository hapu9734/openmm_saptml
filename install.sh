#!/bin/bash
# Build and install the SAPT-ML OpenMM plugin into a conda environment and run the tests.
#
#   bash install.sh                  new environment "saptml": conda-forge OpenMM, compilers, CMake, CUDA headers, SWIG
#   bash install.sh -n NAME          another environment name (created when it does not exist, otherwise reused)
#   bash install.sh -P /path/env     environment by path instead of name
#   bash install.sh -e               the currently active conda environment as it is (needs OpenMM >= 8.2, CMake, a C++
#                                    compiler, SWIG and, for the CUDA platform, the CUDA toolkit headers)
# options: -o OPENMM_VERSION (8.6.1)  -p PYTHON_VERSION (3.11)  -c CUDA_VERSION (from nvidia-smi, else 12)
#          -j JOBS (8)  -t (skip the tests)  -k (keep the build directory)  -m (use mamba instead of conda)
#
# The plugin libraries go into the environment (lib/, lib/plugins/, include/), where OpenMM loads the platform kernels at
# `import openmm`; the saptml Python package is pip-installed into the environment.  Run on a machine with a GPU to build
# and test the CUDA platform (without a GPU the CUDA platform is still built when the CUDA headers are found, but only
# the Reference tests run).
set -Eeuo pipefail
SRC=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
ENV_NAME=saptml; ENV_PATH=""; USE_ACTIVE=0; OMM=8.6.1; PYV=3.11; CUDAV=""; JOBS=8; TESTS=1; KEEP=0; USE_MAMBA=0
while getopts "n:P:eo:p:c:j:tkmh" opt; do
  case $opt in
    n) ENV_NAME=$OPTARG ;; P) ENV_PATH=$OPTARG ;; e) USE_ACTIVE=1 ;; o) OMM=$OPTARG ;; p) PYV=$OPTARG ;;
    c) CUDAV=$OPTARG ;; j) JOBS=$OPTARG ;; t) TESTS=0 ;; k) KEEP=1 ;; m) USE_MAMBA=1 ;;
    *) sed -n '2,14p' "$0"; exit 0 ;;
  esac
done
log() { echo "=== $* ($(date +%H:%M:%S))"; }

CONDA_BASE=$(conda info --base 2>/dev/null || true)
[ -n "$CONDA_BASE" ] && [ -f "$CONDA_BASE/etc/profile.d/conda.sh" ] || { echo "conda not found (run 'conda init' or put conda in PATH)"; exit 1; }
set +u; source "$CONDA_BASE/etc/profile.d/conda.sh"; set -u
CONDA=conda; [ $USE_MAMBA = 1 ] && CONDA=$(command -v mamba)
# conda / mamba with a few retries (package downloads time out now and then)
cinstall() { local k; for k in 1 2 3; do "$CONDA" "$@" && return 0; echo "($CONDA $1 failed, attempt $k)"; sleep 20; done; return 1; }

if [ $USE_ACTIVE = 1 ]; then
  [ -n "${CONDA_PREFIX:-}" ] || { echo "-e: no active conda environment"; exit 1; }
  ACT=$CONDA_PREFIX
else
  if [ -z "$CUDAV" ]; then
    CUDAV=$(nvidia-smi 2>/dev/null | grep -o "CUDA Version: [0-9]*\.[0-9]*" | awk '{print $3}' || true)
    CUDAV=${CUDAV:-12}
  fi
  # CUDA packages no newer than the driver supports (cuda-version pins the CUDA build of OpenMM as well)
  CMAJ=${CUDAV%%.*}; [ "$CMAJ" = "$CUDAV" ] && CPIN="cuda-version=$CMAJ" || CPIN="cuda-version>=$CMAJ,<=$CUDAV"
  PKGS=(python=$PYV openmm=$OMM "$CPIN" cmake make swig cxx-compiler cuda-nvcc cuda-cudart-dev cuda-driver-dev libcufft-dev
        numpy pip setuptools)
  if [ -n "$ENV_PATH" ]; then
    TARGET=(-p "$ENV_PATH"); ACT=$ENV_PATH; EXISTS=0; [ -d "$ENV_PATH/conda-meta" ] && EXISTS=1
  else
    TARGET=(-n "$ENV_NAME"); ACT=$ENV_NAME; EXISTS=0; conda env list | awk '{print $1}' | grep -qx "$ENV_NAME" && EXISTS=1
  fi
  if [ $EXISTS = 1 ]; then
    log "installing the build requirements into the existing environment $ACT"
    cinstall install -y "${TARGET[@]}" --override-channels -c conda-forge "${PKGS[@]}"
  else
    log "creating the conda environment $ACT (OpenMM $OMM, Python $PYV, $CPIN)"
    cinstall create -y "${TARGET[@]}" --override-channels -c conda-forge "${PKGS[@]}"
  fi
  set +u; conda activate "$ACT"; set -u                            # activation scripts may read unset variables
fi
PY=$CONDA_PREFIX/bin/python
OMMV=$($PY -c "import openmm; print(openmm.__version__)")
log "OpenMM $OMMV in $CONDA_PREFIX"

# The plugin's SWIG module must be generated by the SWIG version that wrapped OpenMM itself.
OSWIG=$($PY - <<'EOF'
import os, re, openmm
txt = open(os.path.join(os.path.dirname(openmm.__file__), "openmm.py")).read(4000)
m = re.search(r"Version (\d+\.\d+\.\d+)", txt); print(m.group(1) if m else "")
EOF
)
HSWIG=$(swig -version 2>/dev/null | grep -o "Version [0-9.]*" | awk '{print $2}' || true)
if [ -n "$OSWIG" ] && [ "$OSWIG" != "$HSWIG" ]; then
  log "OpenMM was wrapped with SWIG $OSWIG, found ${HSWIG:-none}: installing swig=$OSWIG"
  cinstall install -y -p "$CONDA_PREFIX" --override-channels -c conda-forge "swig=$OSWIG"
fi

B=$(mktemp -d "${TMPDIR:-/tmp}/saptml_build.XXXXXX")
[ $KEEP = 1 ] && echo "build directory: $B" || trap 'rm -rf "$B"' EXIT
log "configure"
CUDA_ROOT=$CONDA_PREFIX; [ -d "$CONDA_PREFIX/targets/x86_64-linux" ] && CUDA_ROOT=$CONDA_PREFIX/targets/x86_64-linux
cmake -S "$SRC" -B "$B" -DCMAKE_BUILD_TYPE=Release -DOPENMM_DIR="$CONDA_PREFIX" -DCMAKE_INSTALL_PREFIX="$CONDA_PREFIX" \
  -DCUDAToolkit_ROOT="$CUDA_ROOT" -DPYTHON_EXECUTABLE="$PY" -DSWIG_EXECUTABLE="$(command -v swig)" \
  "-DCMAKE_INSTALL_RPATH=\$ORIGIN;\$ORIGIN/..;$CONDA_PREFIX/lib" > "$B/cmake.log" 2>&1 || { tail -40 "$B/cmake.log"; exit 1; }
grep -E "^SAPTML_BUILD_(CUDA_LIB|PYTHON_WRAPPERS)" "$B/CMakeCache.txt" || true
log "build"
cmake --build "$B" -j "$JOBS" > "$B/make.log" 2>&1 || { grep -B3 -A15 -i " error" "$B/make.log" | head -80; exit 1; }
GPU=0; nvidia-smi -L > /dev/null 2>&1 && GPU=1
if [ $TESTS = 1 ]; then
  # C++ tests from the build tree, before installing: OpenMM's own plugins only (an installed copy of this plugin in the
  # same process would register its kernels twice)
  log "C++ tests"
  PD=$B/openmm_plugins; mkdir -p "$PD"
  for f in "$CONDA_PREFIX"/lib/plugins/*; do case $f in *SAPTML*) ;; *) ln -sf "$f" "$PD/" ;; esac; done
  if [ $GPU = 1 ]; then (cd "$B" && OPENMM_PLUGIN_DIR=$PD ctest --output-on-failure) || { echo "C++ tests failed"; exit 1; }
  else (cd "$B" && OPENMM_PLUGIN_DIR=$PD ctest --output-on-failure -R Reference) || { echo "C++ tests failed"; exit 1; }
       echo "(no GPU: CUDA tests skipped)"; fi
fi
log "install"
cmake --install "$B" > "$B/install.log" 2>&1 || { tail -20 "$B/install.log"; exit 1; }
cmake --build "$B" --target PythonInstall > "$B/python.log" 2>&1 || { tail -40 "$B/python.log"; exit 1; }
(cd "$HOME" && $PY -c "import saptml; print('saptml', saptml.__version__, saptml.__file__); print('kernels', saptml.loaded_platforms())")
if [ $TESTS = 1 ]; then
  log "Python tests"
  (cd "$HOME" && $PY "$SRC/tests/test_saptml.py") || { echo "Python tests failed"; exit 1; }
fi
log "done: conda activate $ACT; python $SRC/examples/water256/run.py --pdb $SRC/examples/water256/input.pdb"
